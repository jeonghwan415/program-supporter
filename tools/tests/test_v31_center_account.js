// v3.1 센터 계정(B) 화면 시험 (서버 없이): 저장 상태 단추, 서버 연결 창, 잘못된 키 막기, 글자 크기·화면 밝기, 사용 안내
// 사용: node test_v31_center_account.js <html경로> <스크린샷폴더>
const { chromium } = require('playwright');
const path = require('path');
const [, , htmlPath, outDir] = process.argv;
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
  const errors = [];
  page.on('pageerror', e => errors.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
  page.on('dialog', d => { errors.push('브라우저 기본 창: ' + d.message()); d.dismiss(); });
  await page.goto('file://' + path.resolve(htmlPath) + '?full');
  const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) errors.push('실패: ' + m); };
  ok(!(await page.isVisible('.cc-tour')), '자동 테스트에서는 사용 안내가 자동으로 안 뜸');
  ok((await page.textContent('#ccChip')).includes('이 컴퓨터에만'), '처음 상태: 이 컴퓨터에만 저장');
  await page.click('#ccChip');
  ok(await page.isVisible('.cc-dlg[open] [data-a="wipe"]'), '서버 정보가 없으면 먼저 [내 기록은 어디에?] 안내 창');
  await page.click('[data-a="setup"]');
  ok(await page.isVisible('.cc-dlg[open] #ccUrl'), '[센터 계정 연결 (관리자)]를 누르면 서버 연결 창');
  await page.screenshot({ path: outDir + '/v31_setup.png' });
  await page.fill('#ccUrl', 'http://example.com'); await page.fill('#ccKey', 'x'.repeat(40)); await page.click('[data-a="save"]');
  ok((await page.textContent('#ccErr')).includes('https'), 'https가 아닌 주소는 막음');
  const svc = 'eyJhbGciOiJIUzI1NiJ9.' + Buffer.from('{"role":"service_role"}').toString('base64').replace(/=+$/, '') + '.sig';
  await page.fill('#ccUrl', 'https://abcd.supabase.co'); await page.fill('#ccKey', svc); await page.click('[data-a="save"]');
  ok((await page.textContent('#ccErr')).includes('service_role'), 'service_role 키는 막음');
  await page.click('[data-a="close"]');
  ok(!(await page.isVisible('.cc-dlg[open]')), '[지금은 이 컴퓨터에만 저장]으로 닫힘');
  await page.click('#zoomBtn');
  ok(await page.evaluate(() => document.documentElement.style.zoom) === '1.12', '글자 크게');
  await page.click('#zoomBtn'); await page.click('#zoomBtn');
  ok(await page.evaluate(() => document.documentElement.style.zoom) === '', '세 번 누르면 보통으로');
  await page.click('#themeBtn');
  ok(await page.evaluate(() => document.documentElement.dataset.theme) === 'light', '화면 밝게');
  await page.click('#themeBtn');
  ok(await page.evaluate(() => document.documentElement.dataset.theme) === 'dark', '화면 어둡게');
  await page.screenshot({ path: outDir + '/v31_dark.png' });
  await page.click('#themeBtn');
  await page.click('#tourBtn'); await page.waitForSelector('.cc-tour');
  for (let i = 0; i < 3; i++) await page.keyboard.press('ArrowRight');
  ok((await page.textContent('.cc-tour-n')).startsWith('4 /'), '키보드 →로 다음');
  await page.screenshot({ path: outDir + '/v31_tour.png' });
  await page.keyboard.press('Escape');
  ok(!(await page.isVisible('.cc-tour')), 'Esc로 닫힘');
  await page.reload();
  ok((await page.textContent('#ccChip')).includes('이 컴퓨터에만'), '새로고침해도 그대로');
  console.log('ERRORS:', errors.length ? errors.join('\n') : 'none');
  await browser.close();
  process.exit(errors.length ? 1 : 0);
})();
